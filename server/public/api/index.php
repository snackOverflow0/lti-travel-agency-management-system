<?php
declare(strict_types=1);
// Single API entry point. Application code lives OUTSIDE the web root (see DEPLOYMENT guide); LTI_APP_DIR overrides the default.
$appDir = getenv('LTI_APP_DIR') ?: dirname(__DIR__, 2) . '/app';
require $appDir . '/bootstrap.php';
use LTI\{Http, HttpError, Router, Session};
use LTI\Controllers\{AuthController, BookingController, ContactController, DocumentController, FormController, GroupController, ItineraryController, LibraryController, PortalController, StaffController, SupplierController, TripController};
$dev = ($GLOBALS['LTI_CFG']['env'] ?? 'production') === 'development';
try {
    Session::start();
    $method = $_SERVER['REQUEST_METHOD'];
    $path = '/' . trim((string)($_GET['r'] ?? preg_replace('#^.*?/api#', '', (string)parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH))), '/');
    if (!in_array($method, ['GET', 'HEAD'], true) && !in_array($path, ['/auth/login', '/auth/reset'], true) && !preg_match('#^/public/forms/[a-f0-9]{32}/submit$#', $path)) Session::checkCsrf();
    $r = new Router();
    $r->add('POST', '/auth/login', function () { return AuthController::login(); });
    $r->add('POST', '/auth/logout', function () { return AuthController::logout(); });
    $r->add('GET', '/auth/me', function () { return AuthController::me(); });
    $r->add('POST', '/auth/reset', function () { return AuthController::resetPassword(); });
    $r->add('GET', '/staff', function () { return StaffController::list(); });
    $r->add('PATCH', '/staff/{id}', function ($p) { return StaffController::setActive($p); });
    $r->add('POST', '/staff/{id}/reset-link', function ($p) { return AuthController::createResetLink($p); });
    $r->add('GET', '/contacts', function () { return ContactController::list(); });
    $r->add('POST', '/contacts', function () { return ContactController::create(); });
    $r->add('GET', '/contacts/staff-options', function () { return ContactController::staffOptions(); });
    $r->add('GET', '/contacts/{id}', function ($p) { return ContactController::get($p); });
    $r->add('PUT', '/contacts/{id}', function ($p) { return ContactController::update($p); });
    $r->add('DELETE', '/contacts/{id}', function ($p) { return ContactController::delete($p); });
    $r->add('POST', '/contacts/{id}/portal-account', function ($p) { return PortalController::createAccount($p); });
    $r->add('GET', '/trips', function () { return TripController::list(); });
    $r->add('POST', '/trips', function () { return TripController::create(); });
    $r->add('GET', '/trips/{id}', function ($p) { return TripController::get($p); });
    $r->add('PUT', '/trips/{id}', function ($p) { return TripController::update($p); });
    $r->add('POST', '/trips/{id}/archive', function ($p) { return TripController::archive($p); });
    $r->add('POST', '/trips/{id}/restore', function ($p) { return TripController::archive($p, true); });
    $r->add('PUT', '/trips/{id}/travelers', function ($p) { return TripController::setTravelers($p); });
    $r->add('GET', '/trips/{id}/itinerary', function ($p) { return ItineraryController::get($p); });
    $r->add('PUT', '/trips/{id}/itinerary', function ($p) { return ItineraryController::save($p); });
    $r->add('POST', '/trips/{id}/publish', function ($p) { return ItineraryController::publish($p); });
    $r->add('POST', '/trips/{id}/unpublish', function ($p) { return ItineraryController::unpublish($p); });
    $r->add('GET', '/trips/{id}/versions/{vid}', function ($p) { return ItineraryController::version($p); });
    $r->add('POST', '/trips/{id}/comments', function ($p) { return ItineraryController::staffComment($p); });
    $r->add('GET', '/portal/trips', function () { return PortalController::list(); });
    $r->add('GET', '/portal/trips/{id}', function ($p) { return PortalController::get($p); });
    $r->add('POST', '/portal/trips/{id}/select', function ($p) { return PortalController::select($p); });
    $r->add('POST', '/portal/trips/{id}/approve', function ($p) { return PortalController::approve($p); });
    $r->add('POST', '/portal/trips/{id}/request-changes', function ($p) { return PortalController::requestChanges($p); });
    $r->add('POST', '/portal/trips/{id}/comments', function ($p) { return PortalController::comment($p); });
    $r->add('GET', '/groups', function ($p) { return GroupController::list(); });
    $r->add('POST', '/groups', function ($p) { return GroupController::create(); });
    $r->add('GET', '/groups/{id}', function ($p) { return GroupController::get($p); });
    $r->add('PUT', '/groups/{id}', function ($p) { return GroupController::update($p); });
    $r->add('POST', '/groups/{id}/archive', function ($p) { return GroupController::archive($p); });
    $r->add('POST', '/groups/{id}/restore', function ($p) { return GroupController::archive($p, true); });
    $r->add('PUT', '/groups/{id}/rooms', function ($p) { return GroupController::setRooms($p); });
    $r->add('POST', '/groups/{id}/registrations', function ($p) { return GroupController::register($p); });
    $r->add('PUT', '/groups/{id}/registrations/{rid}', function ($p) { return GroupController::updateRegistration($p); });
    $r->add('POST', '/groups/{id}/registrations/{rid}/cancel', function ($p) { return GroupController::cancelRegistration($p); });
    $r->add('POST', '/groups/{id}/subtrips', function ($p) { return GroupController::createSubTrip($p); });
    $r->add('POST', '/groups/{id}/sync', function ($p) { return GroupController::syncSubTrips($p); });
    $r->add('GET', '/suppliers', function ($p) { return SupplierController::list(); });
    $r->add('POST', '/suppliers', function ($p) { return SupplierController::create(); });
    $r->add('GET', '/suppliers/{id}', function ($p) { return SupplierController::get($p); });
    $r->add('PUT', '/suppliers/{id}', function ($p) { return SupplierController::update($p); });
    $r->add('POST', '/suppliers/{id}/archive', function ($p) { return SupplierController::archive($p); });
    $r->add('POST', '/suppliers/{id}/restore', function ($p) { return SupplierController::archive($p, true); });
    $r->add('PUT', '/suppliers/{id}/contacts', function ($p) { return SupplierController::setContacts($p); });
    $r->add('GET', '/bookings', function ($p) { return BookingController::list(); });
    $r->add('POST', '/bookings', function ($p) { return BookingController::create(); });
    $r->add('GET', '/bookings/{id}', function ($p) { return BookingController::get($p); });
    $r->add('PUT', '/bookings/{id}', function ($p) { return BookingController::update($p); });
    $r->add('PUT', '/bookings/{id}/travelers', function ($p) { return BookingController::setTravelers($p); });
    $r->add('POST', '/bookings/{id}/cancel', function ($p) { return BookingController::cancel($p); });
    $r->add('GET', '/forms', function ($p) { return FormController::list(); });
    $r->add('POST', '/forms', function ($p) { return FormController::create(); });
    $r->add('GET', '/forms/{id}', function ($p) { return FormController::get($p); });
    $r->add('PUT', '/forms/{id}', function ($p) { return FormController::update($p); });
    $r->add('POST', '/forms/{id}/publish', function ($p) { return FormController::setStatus($p, 'published'); });
    $r->add('POST', '/forms/{id}/unpublish', function ($p) { return FormController::setStatus($p, 'draft'); });
    $r->add('POST', '/forms/{id}/archive', function ($p) { return FormController::setStatus($p, 'archived'); });
    $r->add('POST', '/forms/{id}/duplicate', function ($p) { return FormController::duplicate($p); });
    $r->add('GET', '/forms/{id}/submissions', function ($p) { return FormController::submissions($p); });
    $r->add('POST', '/forms/{id}/submissions', function ($p) { return FormController::staffSubmit($p); });
    $r->add('GET', '/forms/{id}/submissions.csv', function ($p) { return FormController::exportCsv($p); });
    $r->add('PUT', '/form-submissions/{id}', function ($p) { return FormController::updateSubmission($p); });
    $r->add('GET', '/public/forms/{token}', function ($p) { return FormController::publicGet($p); });
    $r->add('POST', '/public/forms/{token}/submit', function ($p) { return FormController::publicSubmit($p); });
    $r->add('GET', '/documents', function ($p) { return DocumentController::list(); });
    $r->add('POST', '/documents', function ($p) { return DocumentController::upload(); });
    $r->add('GET', '/documents/{id}', function ($p) { return DocumentController::get($p); });
    $r->add('PUT', '/documents/{id}', function ($p) { return DocumentController::update($p); });
    $r->add('POST', '/documents/{id}/archive', function ($p) { return DocumentController::archive($p); });
    $r->add('GET', '/documents/{id}/download', function ($p) { return DocumentController::download($p); });
    $r->add('GET', '/portal/documents/{id}/download', function ($p) { return DocumentController::portalDownload($p); });
    $r->add('GET', '/library/folders', function ($p) { return LibraryController::folders(); });
    $r->add('POST', '/library/folders', function ($p) { return LibraryController::createFolder(); });
    $r->add('PUT', '/library/folders/{id}', function ($p) { return LibraryController::updateFolder($p); });
    $r->add('DELETE', '/library/folders/{id}', function ($p) { return LibraryController::deleteFolder($p); });
    $r->add('GET', '/library/templates', function ($p) { return LibraryController::list(); });
    $r->add('POST', '/library/templates', function ($p) { return LibraryController::create(); });
    $r->add('GET', '/library/templates/{id}', function ($p) { return LibraryController::get($p); });
    $r->add('PUT', '/library/templates/{id}', function ($p) { return LibraryController::update($p); });
    $r->add('POST', '/library/templates/{id}/duplicate', function ($p) { return LibraryController::duplicate($p); });
    $r->add('POST', '/library/templates/{id}/archive', function ($p) { return LibraryController::archive($p); });
    $r->add('POST', '/library/templates/{id}/restore', function ($p) { return LibraryController::archive($p, true); });
    $r->add('POST', '/library/templates/{id}/use', function ($p) { return LibraryController::useOnTrip($p); });
    $r->add('GET', '/health', function () { return ['ok' => true]; });
    $out = $r->dispatch($method, $path);
    Http::json($out, ($method === 'POST' && in_array($path, ['/contacts', '/trips', '/groups', '/suppliers', '/bookings', '/forms', '/documents', '/library/folders', '/library/templates'], true)) ? 201 : 200);
} catch (HttpError $e) {
    Http::json(['error' => $e->getMessage(), 'fields' => (object)$e->fields], $e->getCode());
} catch (Throwable $e) {
    error_log('[LTI] ' . $e);
    Http::json(['error' => $dev ? $e->getMessage() : 'Unexpected server error'], 500);
}
